/**
 * ISO 3166-1 alpha-2, from whatever a source called the country.
 *
 * **Why this is not the caller's job.** Splitting WooCommerce's `CC:SUBDIVISION` shape already
 * existed in three independent copies before this class did — {@see TaxJurisdiction::idScheme()},
 * and twice in the adapter. A mapping duplicated per caller drifts, and for a content-addressed
 * party a drifted mapping does not fail: it mints a second row that looks perfectly valid, under a
 * different key, and the dedup the table rests on quietly stops happening. One definition, reached
 * from {@see PartyFactNormalizer}, is the same argument that makes `Supplier::partyFacts()` one.
 *
