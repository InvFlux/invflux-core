 * dependency here, never a runtime one: ICU's region data moves with the host's library version and
 * its display names move with the site's locale, so resolving at runtime would make a party's key
 * depend on *which machine computed it* — the one property {@see DocumentPartyRepository} cannot
 * tolerate, since merging two installations rests on identical facts producing identical keys.
