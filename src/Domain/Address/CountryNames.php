/**
 * What each country is called, in each language a document can be written in.
 *
 * **Why this is pinned rather than asked at runtime.** `extension_loaded('intl')` says nothing
 * about whether the host's ICU carries locale data. Slim PHP images routinely ship the
 * English-only bundle, and `Locale::getDisplayRegion('-CH', 'fr')` then answers `Switzerland` — a
 * plausible string, in the wrong language, with nothing anywhere reporting a problem. This
 * project's own `wp-env` cli container is exactly that: ICU 78.1 carrying four locales. So a
 * purchase order written in a supplier's language would have named their country in English on a
 * large class of ordinary hosts, and the feature would have looked like it worked.
 *
 * That is a different argument from the one pinning
 * {@see \Nandan108\InvFlux\Domain\Procurement\CountryCodes} — determinism, because a party's key
 * must not depend on which machine computed it — and it reaches the same place: ICU is a build
 * dependency here, never a runtime one.
 *
 * **English in full, every other language as its differences.** A language's array holds only the
 * regions it renames, which is how a reader sees at a glance that Dutch renames 144 of 250 and
 * Italian 130. A region absent from a language falls through to English rather than to a code.
 *
 * Names are CLDR's standard display forms, so a few read as a catalogue rather than as an envelope
 * (`Congo - Kinshasa`, `Hong Kong SAR China`). Unambiguous and legible, which is the bar for a
 * postal line; hand-correcting 250 names in seven languages is the cost this class exists to avoid.
